    fun t(key: String, lang: String): String =
        auth[lang]?.get(key) ?: all[lang]?.get(key) ?: enAuth[key] ?: en[key] ?: key

    /** Crop / condition names in each language. */
    private val crops = mapOf(
        "Tomato" to Triple("Tomato", "தக்காளி", "टमाटर"),
        "Potato" to Triple("Potato", "உருளைக்கிழங்கு", "आलू"),
        "Pepper,_bell" to Triple("Pepper", "குடைமிளகாய்", "शिमला मिर्च"),
        "Corn_(maize)" to Triple("Maize", "மக்காச்சோளம்", "मक्का"),
        "Rice" to Triple("Rice", "நெல்", "धान"),
    )

    fun cropName(label: String, lang: String): String {
        val key = label.substringBefore("___")
        val tr = crops[key] ?: return key
        return when (lang) { "ta" -> tr.second; "hi" -> tr.third; else -> tr.first }
    }

    /** The plain-English condition name (e.g. "Early blight"). Localised names come from kb.json. */
    fun conditionEn(label: String): String = label.substringAfter("___")
        .replace('_', ' ').trim().replaceFirstChar { it.uppercase() }
        .replace("Spider mites Two-spotted spider mite", "Spider mites")
        .replace("Cercospora leaf spot Gray leaf spot", "Gray leaf spot")
        .replace("BrownSpot", "Brown spot").replace("LeafBlast", "Leaf blast")
